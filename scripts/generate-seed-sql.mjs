/**
 * Generates the curriculum seed migration from lib/mock-data.ts.
 *
 * Transcribing 6 modules, 15 lessons and 9 resources by hand invites typos
 * that only surface as a wrong lesson title in production. This reads the
 * mock data the UI was actually built against and emits SQL from it.
 *
 * Row ids are deterministic UUIDv5 derived from the mock slugs ('mod-0',
 * 'les-1-1'), so the same content always gets the same id in every
 * environment. That is what lets the seed be idempotent and lets test
 * scripts reference known rows.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const NAMESPACE = '1f2d0c4e-9a7b-4f61-8c3d-5e6a7b8c9d01';

function uuidv5(name, namespace = NAMESPACE) {
  const nsBytes = Buffer.from(namespace.replace(/-/g, ''), 'hex');
  const hash = createHash('sha1').update(Buffer.concat([nsBytes, Buffer.from(name, 'utf8')])).digest();
  const b = Buffer.from(hash.subarray(0, 16));
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // RFC 4122 variant
  const h = b.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

const src = readFileSync('lib/mock-data.ts', 'utf8');

/** Slices out one `export const NAME: T = [...]` array literal and evaluates it. */
function extractArray(name) {
  const start = src.indexOf(`export const ${name}`);
  if (start === -1) throw new Error(`${name} not found`);
  // Seek past the `= ` so the `[]` in a `Module[]` type annotation is skipped.
  const eq = src.indexOf('=', start);
  const open = src.indexOf('[', eq);
  let depth = 0;
  let i = open;
  for (; i < src.length; i++) {
    if (src[i] === '[') depth++;
    else if (src[i] === ']') { depth--; if (depth === 0) break; }
  }
  return eval(src.slice(open, i + 1));
}

const modules = extractArray('MOCK_MODULES');
const resources = extractArray('MOCK_RESOURCES');

const q = (v) =>
  v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;

const ORG = uuidv5('org:flag-skool');

// Modules 0-4 ship with the recordings product; module 5 is cohort-only.
// This mirrors lib/data-access.ts: "modules 0 through 4 unlocked, Module 5
// unlocked if cohort tier".
const skuFor = (n) => (n <= 4 ? 'recordings' : 'cohort');

const EXT = { JSON: 'json', ZIP: 'zip', PDF: 'pdf', IPYNB: 'ipynb', DOCX: 'docx', CSV: 'csv', MD: 'md' };

const out = [];
out.push(`-- =============================================================================
-- Flag Skool — curriculum seed
--
-- GENERATED by scripts/generate-seed-sql.mjs from lib/mock-data.ts.
-- Do not hand-edit; change the source data and regenerate.
--
-- Idempotent and safe to re-run against production: every insert is ON
-- CONFLICT DO NOTHING against a natural key, and ids are deterministic
-- UUIDv5 values derived from the content slugs.
--
-- This is fixed course content, which is why it lives in a migration rather
-- than a seed script. Test students and fake transactions do NOT belong here
-- — those live in scripts/seed-test-data.ts.
-- =============================================================================

-- organization -----------------------------------------------------------------
insert into public.organizations (id, slug, name) values
  (${q(ORG)}, 'flag-skool', 'Flag Skool')
on conflict (slug) do nothing;

-- products ---------------------------------------------------------------------
-- Prices mirror config/flagskool.config.ts, in kobo. A cohort purchase grants
-- the recordings sku as well; that is what products.grants_skus is for.
insert into public.products (id, org_id, sku, title, subtitle, price_kobo, grants_skus) values
  (${q(uuidv5('product:recordings'))}, ${q(ORG)}, 'recordings', 'On-Demand Recordings', 'Self-Paced', 10000000, '{}'),
  (${q(uuidv5('product:cohort'))}, ${q(ORG)}, 'cohort', 'Live Cohort 2 + Complete Archive', 'Most Recommended', 15000000, '{recordings}')
on conflict (org_id, sku) do nothing;

-- modules ----------------------------------------------------------------------`);

const moduleValues = modules.map((m) =>
  `  (${q(uuidv5('module:' + m.id))}, ${q(ORG)}, ${q(skuFor(m.number))}, ${m.number}, ${q(m.title)}, ${q(m.description)})`
);
out.push(`insert into public.modules (id, org_id, product_sku, order_index, title, description) values
${moduleValues.join(',\n')}
on conflict (org_id, order_index) do nothing;

-- lessons ----------------------------------------------------------------------
-- bunny_video_id values are the AI Studio placeholders. They are replaced with
-- real Bunny Stream ids in Stage 2; playback is signed server-side either way.
-- published_at is set so the curriculum is visible; entitlement is what gates
-- access, not publication.`);

const lessonValues = [];
for (const m of modules) {
  m.lessons.forEach((l, idx) => {
    lessonValues.push(
      `  (${q(uuidv5('lesson:' + l.id))}, ${q(ORG)}, ${q(uuidv5('module:' + m.id))}, ${idx + 1}, ${q(l.title)}, ${q(l.description)}, ${q(l.bunnyVideoId)}, ${l.durationMinutes * 60}, ${l.isFree ? 'true' : 'false'}, now())`
    );
  });
}
out.push(`insert into public.lessons (id, org_id, module_id, order_index, title, description, bunny_video_id, duration_seconds, is_free_preview, published_at) values
${lessonValues.join(',\n')}
on conflict (module_id, order_index) do nothing;

-- resources --------------------------------------------------------------------`);

const resourceValues = resources.map((r) => {
  const ext = EXT[r.fileFormat] ?? r.fileFormat.toLowerCase();
  const path = `resources/${r.id}.${ext}`;
  return `  (${q(uuidv5('resource:' + r.id))}, ${q(ORG)}, ${q(uuidv5('module:' + r.moduleId))}, ${r.lessonId ? q(uuidv5('lesson:' + r.lessonId)) : 'null'}, ${q(r.title)}, ${q(r.description)}, ${q(r.kind)}, ${q(r.fileFormat)}, ${q(path)}, ${r.sizeBytes})`;
});
out.push(`insert into public.resources (id, org_id, module_id, lesson_id, title, description, kind, file_format, storage_path, size_bytes) values
${resourceValues.join(',\n')}
on conflict (id) do nothing;`);

const sql = out.join('\n');
const target = 'supabase/migrations/20260825000003_seed_curriculum.sql';
writeFileSync(target, sql + '\n');

console.error(`org        ${ORG}`);
console.error(`modules    ${modules.length}`);
console.error(`lessons    ${lessonValues.length}`);
console.error(`resources  ${resources.length}`);
console.error(`free       ${modules.flatMap((m) => m.lessons).filter((l) => l.isFree).length}`);
console.error(`wrote      ${target}`);
